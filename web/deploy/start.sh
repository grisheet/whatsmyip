#!/bin/sh
set -eu

if ! php -r '$key = getenv("APP_KEY") ?: ""; exit(str_starts_with($key, "base64:") && strlen((string) base64_decode(substr($key, 7), true)) === 32 ? 0 : 1);'; then
    echo 'Set APP_KEY to a key generated by php artisan key:generate --show.' >&2
    exit 1
fi

port="${PORT:-8080}"
case "$port" in
    *[!0-9]*|'') echo 'PORT must be a number between 1 and 65535.' >&2; exit 1 ;;
esac
if ! [ "$port" -ge 1 ] || ! [ "$port" -le 65535 ]; then
    echo 'PORT must be a number between 1 and 65535.' >&2
    exit 1
fi

printf 'Define APP_PORT %s\nListen ${APP_PORT}\n' "$port" > /etc/apache2/ports.conf

umask 027
php artisan config:cache --no-interaction
chown root:www-data bootstrap/cache/config.php
chmod 0640 bootstrap/cache/config.php

# Apache workers need to share writable Laravel runtime files.
umask 022
exec apache2-foreground
